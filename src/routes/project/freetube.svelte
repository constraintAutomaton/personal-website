<div>
  <h3><a href="https://github.com/FreeTubeApp/FreeTube">Freetube</a></h3>
  <p>
    Freetube is a cross-platform YouTube client focused on privacy. Contributions include developing
    modules for <a href="https://github.com/FreeTubeApp/FreeTube/pull/1867">displaying viewing statistics (similar to "Stats for Nerds")</a>,
    <a href="https://github.com/FreeTubeApp/FreeTube/pull/1942">searching viewing history and playlists</a>,
    <a href="https://github.com/FreeTubeApp/FreeTube/pull/1971">implementing in-app media downloading</a>, and
    <a href="https://github.com/FreeTubeApp/FreeTube/pull/1812">enhancing the UI styling of various elements</a>.
  </p>
